package purplebook.chap03;
// 관계연산자의 사용예
public class ex04Main {
    public static void main(String[] args) {
        int a = 10, b = 20, c = 10;
        System.out.println("a == b : " + ( a == b ));
        System.out.println("a == c : " + ( a == c ));
        System.out.println("a != b : " + ( a != b ));
        System.out.println("a != c : " + ( a != c ));
        System.out.println("a < b : " + ( a < b ));
        System.out.println("a <= c : " + ( a <= c ));
        System.out.println("a > b : " + ( a > b ));
        System.out.println("a >= c : " + ( a >= c ));
    }
}
