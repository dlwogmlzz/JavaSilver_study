package purplebook.chap02;

public class ex01Main {
    public static void main(String[] args) {
        System.out.println(255);            // 10진수
        System.out.println(0b11111111);     // 2진수
        System.out.println(0377);           // 8진수
        System.out.println(0xff);           // 16진수
        System.out.println(12.33);          // 부동소수점수
        System.out.println(3e4);            // 지수
        System.out.println('A');            // 1문자
        System.out.println('\u3012');       // Unicode
        System.out.println("Hello");        // 문자열
        System.out.println(true);           // 논리값
    }
}
